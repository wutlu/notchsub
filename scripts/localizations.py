def escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main() -> None:
    root = Path(__file__).resolve().parent.parent / "Resources" / "Localization"
    expected = len(KEYS) + 1
    for lang, values in LANGS.items():
        if len(values) != expected:
            raise SystemExit(f"{lang}: {len(values)} values, expected {expected}")
        for key, value in zip(KEYS, values):
            if key.count("%@") != value.count("%@") or key.count("%d") != value.count("%d"):
                raise SystemExit(f"{lang}: placeholder mismatch in {key!r} → {value!r}")
        folder = root / f"{lang}.lproj"
        folder.mkdir(parents=True, exist_ok=True)
        lines = [f'"{escape(k)}" = "{escape(v)}";' for k, v in zip(KEYS, values)]
        (folder / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")
        (folder / "InfoPlist.strings").write_text(
            f'"{USAGE_KEY}" = "{escape(values[-1])}";\n"CFBundleDisplayName" = "NotchSub";\n',
            encoding="utf-8",
        )
    print(f"✓ {len(LANGS)} languages × {len(KEYS)} strings")


if __name__ == "__main__":
    main()
